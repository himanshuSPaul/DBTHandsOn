-- 3. SALES FUNNEL ANALYSIS
-- Track customer journey from first order to repeat purchase
WITH CUSTOMER_JOURNEY AS (
    SELECT 
        TOTAL_ORDERS,
        COUNT(DISTINCT CUSTOMER_ID) as CUSTOMER_COUNT,
        ROUND(100.0 * COUNT(DISTINCT CUSTOMER_ID) / SUM(COUNT(DISTINCT CUSTOMER_ID)) OVER (), 2) as PERCENT_OF_TOTAL
    FROM {{ ref('mart_customers') }}
    WHERE CUSTOMER_ID IS NOT NULL
    GROUP BY TOTAL_ORDERS
)
SELECT 
    CASE 
        WHEN TOTAL_ORDERS = 1 THEN 'One-Time Buyers'
        WHEN TOTAL_ORDERS BETWEEN 2 AND 3 THEN 'Repeat Buyers (2-3)'
        WHEN TOTAL_ORDERS BETWEEN 4 AND 10 THEN 'Loyal (4-10)'
        ELSE 'Very Loyal (10+)'
    END as CUSTOMER_TIER,
    SUM(CUSTOMER_COUNT) as CUSTOMER_COUNT,
    ROUND(SUM(PERCENT_OF_TOTAL), 2) as PERCENT_OF_CUSTOMERS,
    ROUND(SUM(CUSTOMER_COUNT) * 100 / 
        (SELECT COUNT(DISTINCT CUSTOMER_ID) FROM {{ ref('mart_customers') }} WHERE TOTAL_ORDERS = 1), 2) as CONVERSION_FROM_ONE_TIME_PERCENT
FROM CUSTOMER_JOURNEY
GROUP BY CUSTOMER_TIER
ORDER BY CUSTOMER_COUNT DESC;

