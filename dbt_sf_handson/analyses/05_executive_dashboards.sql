-- 6. CUSTOMER SEGMENTATION PERFORMANCE
-- Compare metrics across customer segments
SELECT 
    CUSTOMER_SEGMENT,
    COUNT(DISTINCT CUSTOMER_ID) as SEGMENT_SIZE,
    ROUND(100.0 * COUNT(DISTINCT CUSTOMER_ID) / SUM(COUNT(DISTINCT CUSTOMER_ID)) OVER (), 2) as PERCENT_OF_CUSTOMERS,
    ROUND(SUM(CUSTOMER_LIFETIME_VALUE), 2) as SEGMENT_VALUE,
    ROUND(100.0 * SUM(CUSTOMER_LIFETIME_VALUE) / SUM(SUM(CUSTOMER_LIFETIME_VALUE)) OVER (), 2) as PERCENT_OF_REVENUE,
    ROUND(AVG(CUSTOMER_LIFETIME_VALUE), 2) as AVG_CLV,
    ROUND(AVG(TOTAL_ORDERS), 2) as AVG_ORDERS,
    ROUND(AVG(AVG_ORDER_VALUE), 2) as AVG_AOV,
    COUNT(DISTINCT CASE WHEN CUSTOMER_STATUS = 'Active' THEN CUSTOMER_ID END) as ACTIVE_CUSTOMERS,
    COUNT(DISTINCT CASE WHEN CUSTOMER_STATUS = 'At Risk' THEN CUSTOMER_ID END) as AT_RISK_CUSTOMERS
FROM {{ ref('mart_customers') }}
WHERE CUSTOMER_ID IS NOT NULL
GROUP BY CUSTOMER_SEGMENT
ORDER BY SEGMENT_VALUE DESC;

