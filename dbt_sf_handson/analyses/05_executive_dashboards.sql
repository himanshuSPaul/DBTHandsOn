-- 1. EXECUTIVE SUMMARY - KEY METRICS SNAPSHOT
-- High-level KPIs for business stakeholders
SELECT 
    -- Customer Metrics
    (SELECT COUNT(DISTINCT CUSTOMER_ID) FROM {{ ref('mart_customers') }} WHERE CUSTOMER_ID IS NOT NULL) as TOTAL_CUSTOMERS,
    (SELECT COUNT(DISTINCT CUSTOMER_ID) FROM {{ ref('mart_customers') }} WHERE CUSTOMER_STATUS = 'Active') as ACTIVE_CUSTOMERS,
    (SELECT COUNT(DISTINCT CUSTOMER_ID) FROM {{ ref('mart_customers') }} WHERE CUSTOMER_STATUS = 'At Risk') as AT_RISK_CUSTOMERS,
    (SELECT ROUND(AVG(CUSTOMER_LIFETIME_VALUE), 2) FROM {{ ref('mart_customers') }} WHERE CUSTOMER_ID IS NOT NULL) as AVG_CLV,
    
    -- Order Metrics
    (SELECT COUNT(DISTINCT ORDER_ID) FROM {{ ref('mart_orders') }}) as TOTAL_ORDERS,
    (SELECT ROUND(SUM(ORDER_TOTAL), 2) FROM {{ ref('mart_orders') }}) as TOTAL_REVENUE,
    (SELECT ROUND(AVG(ORDER_TOTAL), 2) FROM {{ ref('mart_orders') }}) as AVG_ORDER_VALUE,
    (SELECT ROUND(SUM(ORDER_TAX_PAID), 2) FROM {{ ref('mart_orders') }}) as TOTAL_TAX_COLLECTED,
    
    -- Product Metrics
    (SELECT COUNT(DISTINCT ITEM_SKU) FROM {{ ref('mart_products') }} WHERE ITEM_SKU IS NOT NULL) as UNIQUE_PRODUCTS,
    (SELECT SUM(TOTAL_ITEMS_SOLD) FROM {{ ref('mart_products') }} WHERE ITEM_SKU IS NOT NULL) as TOTAL_UNITS_SOLD;

