-- 5. PRODUCT PERFORMANCE SCORECARD
-- Comprehensive product metrics for decision making
SELECT 
    ITEM_SKU,
    PRODUCT_NAME,
    PRODUCT_TYPE,
    ROUND(PRODUCT_PRICE, 2) as PRODUCT_PRICE,
    REVENUE_RANK,
    POPULARITY_RANK,
    TOTAL_ITEMS_SOLD,
    ORDERS_CONTAINING_PRODUCT,
    ROUND(PRODUCT_REVENUE, 2) as PRODUCT_REVENUE,
    ROUND(AVG_REVENUE_PER_UNIT, 2) as AVG_UNIT_PRICE,
    PRODUCT_PERFORMANCE_TIER,
    PRODUCT_POPULARITY_TIER,
    CASE 
        WHEN REVENUE_RANK <= 10 AND POPULARITY_RANK <= 10 THEN 'STARS'
        WHEN REVENUE_RANK <= 20 AND POPULARITY_RANK <= 20 THEN 'STRONG'
        WHEN PRODUCT_PERFORMANCE_TIER = 'Low Performer' THEN 'REVIEW'
        ELSE 'STANDARD'
    END as RECOMMENDATION
FROM {{ ref('mart_products') }}
WHERE ITEM_SKU IS NOT NULL
ORDER BY REVENUE_RANK ASC
LIMIT 30;

