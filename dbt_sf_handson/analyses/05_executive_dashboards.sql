-- 2. REVENUE CONCENTRATION ANALYSIS
-- ABC analysis - identify critical revenue drivers
WITH PRODUCT_CONTRIBUTION AS (
    SELECT 
        ITEM_SKU,
        PRODUCT_NAME,
        PRODUCT_REVENUE,
        SUM(PRODUCT_REVENUE) OVER (ORDER BY PRODUCT_REVENUE DESC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) as CUMULATIVE_REVENUE,
        SUM(PRODUCT_REVENUE) OVER () as TOTAL_REVENUE,
        ROW_NUMBER() OVER (ORDER BY PRODUCT_REVENUE DESC) as PRODUCT_RANK
    FROM {{ ref('mart_products') }}
    WHERE ITEM_SKU IS NOT NULL
)
SELECT 
    PRODUCT_RANK,
    ITEM_SKU,
    PRODUCT_NAME,
    PRODUCT_REVENUE,
    ROUND(100.0 * PRODUCT_REVENUE / TOTAL_REVENUE, 2) as PERCENT_OF_REVENUE,
    ROUND(100.0 * CUMULATIVE_REVENUE / TOTAL_REVENUE, 2) as CUMULATIVE_PERCENT,
    CASE 
        WHEN ROUND(100.0 * CUMULATIVE_REVENUE / TOTAL_REVENUE, 2) <= 80 THEN 'A - Critical'
        WHEN ROUND(100.0 * CUMULATIVE_REVENUE / TOTAL_REVENUE, 2) <= 95 THEN 'B - Important'
        ELSE 'C - Minor'
    END as PARETO_CLASSIFICATION
FROM PRODUCT_CONTRIBUTION
WHERE PRODUCT_RANK <= 20;

