-- 4. CUSTOMER VALUE BY COHORT
-- Track customer value progression by acquisition month
WITH COHORT_VALUE AS (
    SELECT 
        DATE_TRUNC(MONTH, FIRST_ORDER_DATE) as ACQUISITION_MONTH,
        COUNT(DISTINCT CUSTOMER_ID) as CUSTOMERS_ACQUIRED,
        ROUND(SUM(CUSTOMER_LIFETIME_VALUE) / NULLIF(COUNT(DISTINCT CUSTOMER_ID), 0), 2) as AVG_CLV,
        SUM(CUSTOMER_LIFETIME_VALUE) as COHORT_TOTAL_VALUE,
        ROUND(AVG(TOTAL_ORDERS), 2) as AVG_ORDERS,
        ROUND(AVG(CUSTOMER_TENURE_DAYS), 0) as AVG_DAYS_AS_CUSTOMER
    FROM {{ ref('mart_customers') }}
    WHERE CUSTOMER_ID IS NOT NULL
    GROUP BY DATE_TRUNC(MONTH, FIRST_ORDER_DATE)
)
SELECT 
    ACQUISITION_MONTH,
    CUSTOMERS_ACQUIRED,
    AVG_CLV,
    COHORT_TOTAL_VALUE,
    AVG_ORDERS,
    AVG_DAYS_AS_CUSTOMER,
    ROUND(COHORT_TOTAL_VALUE / NULLIF(CUSTOMERS_ACQUIRED, 0), 2) as VALUE_PER_CUSTOMER_ACQUIRED
FROM COHORT_VALUE
ORDER BY ACQUISITION_MONTH DESC;

