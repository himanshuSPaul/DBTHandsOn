-- 4. CHURN RISK SCORING
-- Identify customers most likely to leave
SELECT 
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CUSTOMER_LIFETIME_VALUE,
    TOTAL_ORDERS,
    RECENCY_DAYS,
    CUSTOMER_TENURE_DAYS,
    AVG_ORDER_VALUE,
    LAST_ORDER_DATE,
    CASE 
        WHEN RECENCY_DAYS > (CUSTOMER_TENURE_DAYS / 2) THEN 'HIGH RISK'
        WHEN RECENCY_DAYS > (CUSTOMER_TENURE_DAYS / 3) THEN 'MEDIUM RISK'
        ELSE 'LOW RISK'
    END as CHURN_RISK,
    ROUND(RECENCY_DAYS / NULLIF(CUSTOMER_TENURE_DAYS, 0), 2) as INACTIVE_RATIO,
    DATEDIFF(DAY, LAST_ORDER_DATE, CURRENT_DATE()) as DAYS_INACTIVE
FROM {{ ref('mart_customers') }}
WHERE CUSTOMER_ID IS NOT NULL
  AND TOTAL_ORDERS > 1
  AND CUSTOMER_STATUS != 'Active'
ORDER BY RECENCY_DAYS DESC;

