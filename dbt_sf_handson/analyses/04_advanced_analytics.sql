-- 3. CUSTOMER COHORT ANALYSIS
-- Track customer behavior by acquisition cohort
WITH CUSTOMER_COHORTS AS (
    SELECT 
        DATE_TRUNC(MONTH, FIRST_ORDER_DATE) as COHORT_MONTH,
        CUSTOMER_ID,
        CUSTOMER_NAME,
        CUSTOMER_LIFETIME_VALUE,
        TOTAL_ORDERS,
        CUSTOMER_STATUS
    FROM {{ ref('mart_customers') }}
    WHERE CUSTOMER_ID IS NOT NULL
)
SELECT 
    COHORT_MONTH,
    COUNT(DISTINCT CUSTOMER_ID) as COHORT_SIZE,
    COUNT(DISTINCT CASE WHEN CUSTOMER_STATUS = 'Active' THEN CUSTOMER_ID END) as ACTIVE_CUSTOMERS,
    ROUND(100.0 * COUNT(DISTINCT CASE WHEN CUSTOMER_STATUS = 'Active' THEN CUSTOMER_ID END) 
        / NULLIF(COUNT(DISTINCT CUSTOMER_ID), 0), 2) as RETENTION_RATE,
    ROUND(SUM(CUSTOMER_LIFETIME_VALUE) / NULLIF(COUNT(DISTINCT CUSTOMER_ID), 0), 2) as AVG_CLV_PER_CUSTOMER,
    ROUND(AVG(TOTAL_ORDERS), 2) as AVG_ORDERS,
    SUM(CUSTOMER_LIFETIME_VALUE) as COHORT_TOTAL_VALUE
FROM CUSTOMER_COHORTS
GROUP BY COHORT_MONTH
ORDER BY COHORT_MONTH DESC;

