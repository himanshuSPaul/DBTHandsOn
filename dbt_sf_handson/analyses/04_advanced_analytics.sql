-- 5. REVENUE GROWTH ANALYSIS
-- Month-over-month growth trends
WITH MONTHLY_REVENUE AS (
    SELECT 
        ORDER_YEAR,
        ORDER_MONTH,
        SUM(ORDER_TOTAL) as MONTHLY_REVENUE,
        COUNT(DISTINCT ORDER_ID) as MONTHLY_ORDERS,
        COUNT(DISTINCT ORDER_CUSTOMER) as MONTHLY_CUSTOMERS
    FROM {{ ref('mart_orders') }}
    WHERE ORDER_DATE IS NOT NULL
    GROUP BY ORDER_YEAR, ORDER_MONTH
)
SELECT 
    ORDER_YEAR,
    ORDER_MONTH,
    MONTHLY_REVENUE,
    LAG(MONTHLY_REVENUE) OVER (ORDER BY ORDER_YEAR, ORDER_MONTH) as PREV_MONTH_REVENUE,
    ROUND(((MONTHLY_REVENUE - LAG(MONTHLY_REVENUE) OVER (ORDER BY ORDER_YEAR, ORDER_MONTH)) 
        / NULLIF(LAG(MONTHLY_REVENUE) OVER (ORDER BY ORDER_YEAR, ORDER_MONTH), 0)) * 100, 2) as MOM_GROWTH_PERCENT,
    MONTHLY_ORDERS,
    MONTHLY_CUSTOMERS,
    ROUND(MONTHLY_REVENUE / NULLIF(MONTHLY_ORDERS, 0), 2) as AVG_ORDER_VALUE
FROM MONTHLY_REVENUE
ORDER BY ORDER_YEAR DESC, ORDER_MONTH DESC;

