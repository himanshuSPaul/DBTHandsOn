-- 6. CUSTOMER-PRODUCT AFFINITY
-- Which customer segments buy which products
WITH CUSTOMER_PRODUCT_AFFINITY AS (
    SELECT 
        c.CUSTOMER_SEGMENT,
        c.CUSTOMER_STATUS,
        oi.PRODUCT_NAME,
        oi.PRODUCT_TYPE,
        COUNT(DISTINCT oi.ORDER_ID) as PURCHASE_COUNT,
        SUM(oi.ITEM_AMOUNT) as SEGMENT_PRODUCT_REVENUE,
        COUNT(DISTINCT c.CUSTOMER_ID) as CUSTOMER_COUNT
    FROM {{ ref('mart_orders_by_customer') }} oc
    INNER JOIN {{ ref('mart_customers') }} c ON oc.CUSTOMER_ID = c.CUSTOMER_ID
    INNER JOIN {{ ref('int_orders_items_joined') }} oi ON oc.ORDER_ID = oi.ORDER_ID
    WHERE oc.ORDER_ID IS NOT NULL
    GROUP BY c.CUSTOMER_SEGMENT, c.CUSTOMER_STATUS, oi.PRODUCT_NAME, oi.PRODUCT_TYPE
)
SELECT 
    CUSTOMER_SEGMENT,
    CUSTOMER_STATUS,
    PRODUCT_NAME,
    PRODUCT_TYPE,
    PURCHASE_COUNT,
    ROUND(SEGMENT_PRODUCT_REVENUE, 2) as REVENUE,
    CUSTOMER_COUNT,
    RANK() OVER (PARTITION BY CUSTOMER_SEGMENT, CUSTOMER_STATUS ORDER BY SEGMENT_PRODUCT_REVENUE DESC) as PRODUCT_RANK
FROM CUSTOMER_PRODUCT_AFFINITY
WHERE PRODUCT_RANK <= 10
ORDER BY CUSTOMER_SEGMENT, CUSTOMER_STATUS, PRODUCT_RANK;

