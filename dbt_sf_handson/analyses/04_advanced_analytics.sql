-- 7. BASKET ANALYSIS
-- Average order composition and value
WITH BASKET_METRICS AS (
    SELECT 
        ORDER_ID,
        ORDER_CUSTOMER,
        ORDER_TOTAL,
        COUNT(DISTINCT ITEM_SKU) as UNIQUE_PRODUCTS,
        COUNT(ITEM_ID) as TOTAL_ITEMS,
        COUNT(DISTINCT PRODUCT_TYPE) as PRODUCT_TYPES
    FROM {{ ref('int_orders_items_joined') }}
    GROUP BY ORDER_ID, ORDER_CUSTOMER, ORDER_TOTAL
)
SELECT 
    CASE 
        WHEN UNIQUE_PRODUCTS = 1 THEN 'Single Product'
        WHEN UNIQUE_PRODUCTS BETWEEN 2 AND 3 THEN '2-3 Products'
        WHEN UNIQUE_PRODUCTS BETWEEN 4 AND 5 THEN '4-5 Products'
        ELSE '6+ Products'
    END as BASKET_COMPOSITION,
    COUNT(DISTINCT ORDER_ID) as BASKET_COUNT,
    ROUND(100.0 * COUNT(DISTINCT ORDER_ID) / SUM(COUNT(DISTINCT ORDER_ID)) OVER (), 2) as PERCENT_OF_ORDERS,
    ROUND(AVG(ORDER_TOTAL), 2) as AVG_BASKET_VALUE,
    ROUND(AVG(TOTAL_ITEMS), 2) as AVG_ITEMS_PER_BASKET,
    MIN(ORDER_TOTAL) as MIN_BASKET_VALUE,
    MAX(ORDER_TOTAL) as MAX_BASKET_VALUE,
    SUM(ORDER_TOTAL) as TOTAL_REVENUE
FROM BASKET_METRICS
GROUP BY BASKET_COMPOSITION
ORDER BY AVG_BASKET_VALUE DESC;
