-- 2. CUSTOMER LIFETIME VALUE PROJECTION
-- Estimate future revenue based on past behavior
SELECT 
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CUSTOMER_LIFETIME_VALUE,
    TOTAL_ORDERS,
    AVG_ORDER_VALUE,
    CUSTOMER_TENURE_DAYS,
    CUSTOMER_ORDER_FREQUENCY_ANNUAL,
    ROUND(AVG_ORDER_VALUE * CUSTOMER_ORDER_FREQUENCY_ANNUAL * 2, 2) as PROJECTED_CLV_2_YEARS,
    ROUND(AVG_ORDER_VALUE * CUSTOMER_ORDER_FREQUENCY_ANNUAL * 3, 2) as PROJECTED_CLV_3_YEARS,
    CASE 
        WHEN CUSTOMER_ORDER_FREQUENCY_ANNUAL >= 12 THEN 'High Engagement'
        WHEN CUSTOMER_ORDER_FREQUENCY_ANNUAL >= 4 THEN 'Medium Engagement'
        ELSE 'Low Engagement'
    END as ENGAGEMENT_LEVEL
FROM {{ ref('mart_customers') }}
WHERE CUSTOMER_ID IS NOT NULL
  AND CUSTOMER_ORDER_FREQUENCY_ANNUAL > 0
ORDER BY PROJECTED_CLV_3_YEARS DESC;

