-- 1. RFM ANALYSIS (RECENCY, FREQUENCY, MONETARY)
-- Segment customers using classic RFM scoring
WITH CUSTOMER_RFM AS (
    SELECT 
        CUSTOMER_ID,
        CUSTOMER_NAME,
        RECENCY_DAYS,
        TOTAL_ORDERS as FREQUENCY,
        CUSTOMER_LIFETIME_VALUE as MONETARY,
        NTILE(5) OVER (ORDER BY RECENCY_DAYS DESC) as RECENCY_SCORE,
        NTILE(5) OVER (ORDER BY TOTAL_ORDERS ASC) as FREQUENCY_SCORE,
        NTILE(5) OVER (ORDER BY CUSTOMER_LIFETIME_VALUE ASC) as MONETARY_SCORE
    FROM {{ ref('mart_customers') }}
    WHERE CUSTOMER_ID IS NOT NULL
)
SELECT 
    CUSTOMER_ID,
    CUSTOMER_NAME,
    RECENCY_DAYS,
    FREQUENCY,
    MONETARY,
    RECENCY_SCORE,
    FREQUENCY_SCORE,
    MONETARY_SCORE,
    (RECENCY_SCORE + FREQUENCY_SCORE + MONETARY_SCORE) as RFM_TOTAL_SCORE,
    CASE 
        WHEN (RECENCY_SCORE + FREQUENCY_SCORE + MONETARY_SCORE) >= 13 THEN 'Champions'
        WHEN (RECENCY_SCORE + FREQUENCY_SCORE + MONETARY_SCORE) >= 10 THEN 'Loyal Customers'
        WHEN (RECENCY_SCORE + FREQUENCY_SCORE + MONETARY_SCORE) >= 7 THEN 'Potential Loyalists'
        WHEN RECENCY_SCORE >= 4 THEN 'Recent Customers'
        ELSE 'At Risk / Dormant'
    END as RFM_SEGMENT
FROM CUSTOMER_RFM
ORDER BY RFM_TOTAL_SCORE DESC;

